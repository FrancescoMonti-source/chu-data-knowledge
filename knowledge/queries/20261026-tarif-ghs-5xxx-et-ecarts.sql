-- person_data: masked
-- purpose: éprouver tarif-ghs-par-ghm-et-code-ghs (#103, étape 9 du plan) : dire ce que sont les GHS 5xxx de PMSI_LIB_GHS_TARIF et si des RSS du CHU y sont groupés ; mesurer, de 2022 à août 2026, à quel point le PRIX joint par le GHM et le CODE_GHS égale MONTANT_GHS, et combien de couples GHM et CODE_GHS ont plusieurs lignes valides à une même date
-- Oracle, schéma CORA_REC. Colonnes de PMSI_LIB_GHS_TARIF d'après 20261015-catalogue-referentiels-resultat. Ligne valide à la date d : DATE_DEBUT <= d <= DATE_FIN (referentiels-pmsi-dans-cora).
-- Six niveaux. Référentiel, aucune personne : EXEMPLES (lignes valides au 2026-06-30 des GHM 04C021 et 05C021, avec leurs colonnes descriptives) ; CHIFFRE (lignes valides au 2026-06-30 par premier chiffre du CODE_GHS : lignes, GHS et GHM comptés, lignes de borne haute 999, lignes de GET_LIBELLE 'O') ; LIBELLES_5 (les cinq LIBELLE_GHS les plus fréquents parmi les lignes de GHS 5xxx valides au 2026-06-30) ; COUPLES (couples GHM et CODE_GHS valides au 2026-06-30 par nombre de lignes, et ceux dont les lignes ont des PRIX différents). Personnes, masqué : ECARTS (par année de fin, RSS groupés hors CMD 90 et GHS 9999, de MONTANT_GHS positif ; N_AVEC_LIGNE : RSS dont le GHM et le CODE_GHS trouvent une ligne valide à leur DATE_FIN ; N_PLUSIEURS_LIGNES : RSS qui en trouvent plusieurs ; N_EGAL : RSS dont MONTANT_GHS et le plus petit PRIX de leur couple diffèrent de moins de 0,50 € ; centiles 5, 25, 50, 75 et 95 de MONTANT_GHS / PRIX) ; RSS_5XXX (par année de fin, RSS groupés dans un GHS 5xxx, quel que soit leur montant ; ceux qui trouvent une ligne ; médiane de MONTANT_GHS / PRIX).
-- Comptes du référentiel nommés …_COMPTES : ce ne sont pas des personnes. Masquage : chaque effectif de RSS < 10 sort en <10 ; centiles et médiane vides sous 10 RSS. Suppression secondaire (règle 4) : N_RSS sort en « masqué » quand N_RSS moins N_AVEC_LIGNE vaut de 1 à 9 ; N_EGAL sort en « masqué » quand N_AVEC_LIGNE moins N_EGAL vaut de 1 à 9. Aucune ligne de total : les années ne se somment pas dans le résultat.
WITH t AS (
  SELECT /*+ MATERIALIZE */ TRIM(GHS) AS GHM6, TRIM(CODE_GHS) AS CODE_GHS, TRIM(LIBELLE_GHS) AS LIBELLE_GHS,
         TRIM(TYPE_ACTIVITE) AS TYPE_ACT, PRIX, BAS, HAUT, TRIM(GET_LIBELLE) AS GET_LIB,
         TARIF_BORNE, MNT_FORFAIT_EXB, MNT_JOUR_EXB, DMS_PUBLIC, DMS_PRIVE,
         TRUNC(DATE_DEBUT) AS DD, TRUNC(DATE_FIN) AS DF
  FROM CORA_REC.PMSI_LIB_GHS_TARIF
),
t26 AS (
  SELECT /*+ MATERIALIZE */ GHM6, CODE_GHS, LIBELLE_GHS, TYPE_ACT, PRIX, BAS, HAUT, GET_LIB, TARIF_BORNE, MNT_FORFAIT_EXB, MNT_JOUR_EXB, DMS_PUBLIC, DMS_PRIVE, DD, DF
  FROM t WHERE DD <= DATE '2026-06-30' AND DF >= DATE '2026-06-30'
),
exemples AS (
  SELECT 'EXEMPLES' AS NIVEAU, GHM6 AS CLE, CODE_GHS, LIBELLE_GHS, TYPE_ACT, PRIX, BAS, HAUT, GET_LIB,
         TARIF_BORNE, MNT_FORFAIT_EXB, MNT_JOUR_EXB, DMS_PUBLIC, DMS_PRIVE,
         CAST(NULL AS NUMBER) AS LIGNES_COMPTEES, CAST(NULL AS NUMBER) AS GHS_COMPTES, CAST(NULL AS NUMBER) AS GHM_COMPTES,
         CAST(NULL AS NUMBER) AS HAUT_999_COMPTEES, CAST(NULL AS NUMBER) AS GET_O_COMPTEES, CAST(NULL AS NUMBER) AS PRIX_DIFFERENTS_COMPTES
  FROM t26
  WHERE GHM6 IN ('04C021', '05C021')
),
chiffre AS (
  SELECT 'CHIFFRE' AS NIVEAU, SUBSTR(CODE_GHS, 1, 1) AS CLE,
         CAST(NULL AS VARCHAR2(10)) AS CODE_GHS, CAST(NULL AS VARCHAR2(200)) AS LIBELLE_GHS, CAST(NULL AS VARCHAR2(10)) AS TYPE_ACT,
         CAST(NULL AS NUMBER) AS PRIX, CAST(NULL AS NUMBER) AS BAS, CAST(NULL AS NUMBER) AS HAUT, CAST(NULL AS VARCHAR2(10)) AS GET_LIB,
         CAST(NULL AS NUMBER) AS TARIF_BORNE, CAST(NULL AS NUMBER) AS MNT_FORFAIT_EXB, CAST(NULL AS NUMBER) AS MNT_JOUR_EXB,
         CAST(NULL AS NUMBER) AS DMS_PUBLIC, CAST(NULL AS NUMBER) AS DMS_PRIVE,
         COUNT(*) AS LIGNES_COMPTEES, COUNT(DISTINCT CODE_GHS) AS GHS_COMPTES, COUNT(DISTINCT GHM6) AS GHM_COMPTES,
         SUM(CASE WHEN HAUT = 999 THEN 1 ELSE 0 END) AS HAUT_999_COMPTEES,
         SUM(CASE WHEN GET_LIB = 'O' THEN 1 ELSE 0 END) AS GET_O_COMPTEES,
         CAST(NULL AS NUMBER) AS PRIX_DIFFERENTS_COMPTES
  FROM t26
  GROUP BY SUBSTR(CODE_GHS, 1, 1)
),
libelles AS (
  SELECT 'LIBELLES_5' AS NIVEAU, CAST(NULL AS VARCHAR2(10)) AS CLE,
         CAST(NULL AS VARCHAR2(10)) AS CODE_GHS, LIBELLE_GHS, CAST(NULL AS VARCHAR2(10)) AS TYPE_ACT,
         CAST(NULL AS NUMBER) AS PRIX, CAST(NULL AS NUMBER) AS BAS, CAST(NULL AS NUMBER) AS HAUT, CAST(NULL AS VARCHAR2(10)) AS GET_LIB,
         CAST(NULL AS NUMBER) AS TARIF_BORNE, CAST(NULL AS NUMBER) AS MNT_FORFAIT_EXB, CAST(NULL AS NUMBER) AS MNT_JOUR_EXB,
         CAST(NULL AS NUMBER) AS DMS_PUBLIC, CAST(NULL AS NUMBER) AS DMS_PRIVE,
         LIGNES_COMPTEES, GHS_COMPTES, CAST(NULL AS NUMBER) AS GHM_COMPTES,
         CAST(NULL AS NUMBER) AS HAUT_999_COMPTEES, CAST(NULL AS NUMBER) AS GET_O_COMPTEES, CAST(NULL AS NUMBER) AS PRIX_DIFFERENTS_COMPTES
  FROM (
    SELECT LIBELLE_GHS, COUNT(*) AS LIGNES_COMPTEES, COUNT(DISTINCT CODE_GHS) AS GHS_COMPTES,
           ROW_NUMBER() OVER (ORDER BY COUNT(*) DESC, LIBELLE_GHS) AS RG
    FROM t26
    WHERE CODE_GHS LIKE '5___'
    GROUP BY LIBELLE_GHS
  )
  WHERE RG <= 5
),
couples AS (
  SELECT 'COUPLES' AS NIVEAU, CASE WHEN L = 1 THEN '1 ligne' ELSE '2 lignes ou plus' END AS CLE,
         CAST(NULL AS VARCHAR2(10)) AS CODE_GHS, CAST(NULL AS VARCHAR2(200)) AS LIBELLE_GHS, CAST(NULL AS VARCHAR2(10)) AS TYPE_ACT,
         CAST(NULL AS NUMBER) AS PRIX, CAST(NULL AS NUMBER) AS BAS, CAST(NULL AS NUMBER) AS HAUT, CAST(NULL AS VARCHAR2(10)) AS GET_LIB,
         CAST(NULL AS NUMBER) AS TARIF_BORNE, CAST(NULL AS NUMBER) AS MNT_FORFAIT_EXB, CAST(NULL AS NUMBER) AS MNT_JOUR_EXB,
         CAST(NULL AS NUMBER) AS DMS_PUBLIC, CAST(NULL AS NUMBER) AS DMS_PRIVE,
         COUNT(*) AS LIGNES_COMPTEES, CAST(NULL AS NUMBER) AS GHS_COMPTES, CAST(NULL AS NUMBER) AS GHM_COMPTES,
         CAST(NULL AS NUMBER) AS HAUT_999_COMPTEES, CAST(NULL AS NUMBER) AS GET_O_COMPTEES,
         SUM(CASE WHEN P > 1 THEN 1 ELSE 0 END) AS PRIX_DIFFERENTS_COMPTES
  FROM (SELECT GHM6, CODE_GHS, COUNT(*) AS L, COUNT(DISTINCT PRIX) AS P FROM t26 GROUP BY GHM6, CODE_GHS)
  GROUP BY CASE WHEN L = 1 THEN '1 ligne' ELSE '2 lignes ou plus' END
),
rss AS (
  SELECT /*+ MATERIALIZE */ ROWNUM AS RN, TO_CHAR(r.DATE_FIN, 'YYYY') AS ANNEE,
         TRIM(r.CODE_CMD) || TRIM(r.CODE_GHM) AS GHM6, TRIM(r.CODE_GHS) AS CODE_GHS,
         TRUNC(r.DATE_FIN) AS D, r.MONTANT_GHS
  FROM CORA_REC.TB_SYNTH_RSS r
  WHERE r.DATE_FIN >= DATE '2022-01-01' AND r.DATE_FIN < DATE '2026-09-01'
    AND TRIM(r.CODE_GHM) IS NOT NULL AND TRIM(r.CODE_CMD) <> '90'
    AND TRIM(r.CODE_GHS) <> '9999'
),
lien AS (
  SELECT rss.RN, COUNT(*) AS L, MIN(t.PRIX) AS PRIX
  FROM rss JOIN t ON t.GHM6 = rss.GHM6 AND t.CODE_GHS = rss.CODE_GHS AND t.DD <= rss.D AND t.DF >= rss.D
  GROUP BY rss.RN
),
rp AS (
  SELECT /*+ MATERIALIZE */ rss.ANNEE, rss.CODE_GHS, rss.MONTANT_GHS, lien.L, lien.PRIX,
         CASE WHEN lien.PRIX > 0 AND rss.MONTANT_GHS > 0 THEN rss.MONTANT_GHS / lien.PRIX END AS RATIO
  FROM rss LEFT JOIN lien ON lien.RN = rss.RN
),
ea AS (
  SELECT ANNEE, COUNT(*) AS N, COUNT(L) AS NL, SUM(CASE WHEN L > 1 THEN 1 ELSE 0 END) AS NP,
         SUM(CASE WHEN L IS NOT NULL AND ABS(MONTANT_GHS - PRIX) < 0.5 THEN 1 ELSE 0 END) AS NE,
         PERCENTILE_CONT(0.05) WITHIN GROUP (ORDER BY RATIO) AS P05,
         PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY RATIO) AS P25,
         PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY RATIO) AS P50,
         PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY RATIO) AS P75,
         PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY RATIO) AS P95
  FROM rp
  WHERE MONTANT_GHS > 0
  GROUP BY ANNEE
),
cinq AS (
  SELECT ANNEE, COUNT(*) AS N, COUNT(L) AS NL, MEDIAN(RATIO) AS P50
  FROM rp
  WHERE CODE_GHS LIKE '5___'
  GROUP BY ANNEE
),
personnes AS (
  SELECT 'ECARTS' AS NIVEAU, ANNEE AS CLE,
         CASE WHEN N < 10 THEN '<10' WHEN N - NL BETWEEN 1 AND 9 THEN 'masqué' ELSE TO_CHAR(N) END AS N_RSS,
         CASE WHEN NL < 10 THEN '<10' ELSE TO_CHAR(NL) END AS N_AVEC_LIGNE,
         CASE WHEN NP < 10 THEN '<10' ELSE TO_CHAR(NP) END AS N_PLUSIEURS_LIGNES,
         CASE WHEN NE < 10 THEN '<10' WHEN NL - NE BETWEEN 1 AND 9 THEN 'masqué' ELSE TO_CHAR(NE) END AS N_EGAL,
         CASE WHEN NL >= 10 THEN ROUND(P05, 3) END AS RATIO_P05,
         CASE WHEN NL >= 10 THEN ROUND(P25, 3) END AS RATIO_P25,
         CASE WHEN NL >= 10 THEN ROUND(P50, 3) END AS RATIO_MED,
         CASE WHEN NL >= 10 THEN ROUND(P75, 3) END AS RATIO_P75,
         CASE WHEN NL >= 10 THEN ROUND(P95, 3) END AS RATIO_P95
  FROM ea
  UNION ALL
  SELECT 'RSS_5XXX', ANNEE,
         CASE WHEN N < 10 THEN '<10' WHEN N - NL BETWEEN 1 AND 9 THEN 'masqué' ELSE TO_CHAR(N) END,
         CASE WHEN NL < 10 THEN '<10' ELSE TO_CHAR(NL) END,
         CAST(NULL AS VARCHAR2(10)), CAST(NULL AS VARCHAR2(10)),
         CAST(NULL AS NUMBER), CAST(NULL AS NUMBER),
         CASE WHEN NL >= 10 THEN ROUND(P50, 3) END,
         CAST(NULL AS NUMBER), CAST(NULL AS NUMBER)
  FROM cinq
),
referentiel AS (
  SELECT NIVEAU, CLE, CODE_GHS, LIBELLE_GHS, TYPE_ACT, PRIX, BAS, HAUT, GET_LIB, TARIF_BORNE, MNT_FORFAIT_EXB, MNT_JOUR_EXB, DMS_PUBLIC, DMS_PRIVE,
         LIGNES_COMPTEES, GHS_COMPTES, GHM_COMPTES, HAUT_999_COMPTEES, GET_O_COMPTEES, PRIX_DIFFERENTS_COMPTES FROM exemples
  UNION ALL
  SELECT NIVEAU, CLE, CODE_GHS, LIBELLE_GHS, TYPE_ACT, PRIX, BAS, HAUT, GET_LIB, TARIF_BORNE, MNT_FORFAIT_EXB, MNT_JOUR_EXB, DMS_PUBLIC, DMS_PRIVE,
         LIGNES_COMPTEES, GHS_COMPTES, GHM_COMPTES, HAUT_999_COMPTEES, GET_O_COMPTEES, PRIX_DIFFERENTS_COMPTES FROM chiffre
  UNION ALL
  SELECT NIVEAU, CLE, CODE_GHS, LIBELLE_GHS, TYPE_ACT, PRIX, BAS, HAUT, GET_LIB, TARIF_BORNE, MNT_FORFAIT_EXB, MNT_JOUR_EXB, DMS_PUBLIC, DMS_PRIVE,
         LIGNES_COMPTEES, GHS_COMPTES, GHM_COMPTES, HAUT_999_COMPTEES, GET_O_COMPTEES, PRIX_DIFFERENTS_COMPTES FROM libelles
  UNION ALL
  SELECT NIVEAU, CLE, CODE_GHS, LIBELLE_GHS, TYPE_ACT, PRIX, BAS, HAUT, GET_LIB, TARIF_BORNE, MNT_FORFAIT_EXB, MNT_JOUR_EXB, DMS_PUBLIC, DMS_PRIVE,
         LIGNES_COMPTEES, GHS_COMPTES, GHM_COMPTES, HAUT_999_COMPTEES, GET_O_COMPTEES, PRIX_DIFFERENTS_COMPTES FROM couples
)
SELECT '20261026-tarif-ghs-5xxx-et-ecarts' AS query_id,
       SYS_CONTEXT('USERENV', 'DB_NAME') AS database_name,
       TO_CHAR(SYSTIMESTAMP, 'YYYY-MM-DD HH24:MI') AS run_at,
       x.NIVEAU, x.CLE, x.CODE_GHS, x.LIBELLE_GHS, x.TYPE_ACT, x.PRIX, x.BAS, x.HAUT, x.GET_LIB,
       x.TARIF_BORNE, x.MNT_FORFAIT_EXB, x.MNT_JOUR_EXB, x.DMS_PUBLIC, x.DMS_PRIVE,
       x.LIGNES_COMPTEES, x.GHS_COMPTES, x.GHM_COMPTES, x.HAUT_999_COMPTEES, x.GET_O_COMPTEES, x.PRIX_DIFFERENTS_COMPTES,
       x.N_RSS, x.N_AVEC_LIGNE, x.N_PLUSIEURS_LIGNES, x.N_EGAL,
       x.RATIO_P05, x.RATIO_P25, x.RATIO_MED, x.RATIO_P75, x.RATIO_P95
FROM (
  SELECT NIVEAU, CLE, CODE_GHS, LIBELLE_GHS, TYPE_ACT, PRIX, BAS, HAUT, GET_LIB,
         TARIF_BORNE, MNT_FORFAIT_EXB, MNT_JOUR_EXB, DMS_PUBLIC, DMS_PRIVE,
         LIGNES_COMPTEES, GHS_COMPTES, GHM_COMPTES, HAUT_999_COMPTEES, GET_O_COMPTEES, PRIX_DIFFERENTS_COMPTES,
         CAST(NULL AS VARCHAR2(10)) AS N_RSS, CAST(NULL AS VARCHAR2(10)) AS N_AVEC_LIGNE,
         CAST(NULL AS VARCHAR2(10)) AS N_PLUSIEURS_LIGNES, CAST(NULL AS VARCHAR2(10)) AS N_EGAL,
         CAST(NULL AS NUMBER) AS RATIO_P05, CAST(NULL AS NUMBER) AS RATIO_P25, CAST(NULL AS NUMBER) AS RATIO_MED,
         CAST(NULL AS NUMBER) AS RATIO_P75, CAST(NULL AS NUMBER) AS RATIO_P95
  FROM referentiel
  UNION ALL
  SELECT NIVEAU, CLE, CAST(NULL AS VARCHAR2(10)), CAST(NULL AS VARCHAR2(200)), CAST(NULL AS VARCHAR2(10)),
         CAST(NULL AS NUMBER), CAST(NULL AS NUMBER), CAST(NULL AS NUMBER), CAST(NULL AS VARCHAR2(10)),
         CAST(NULL AS NUMBER), CAST(NULL AS NUMBER), CAST(NULL AS NUMBER), CAST(NULL AS NUMBER), CAST(NULL AS NUMBER),
         CAST(NULL AS NUMBER), CAST(NULL AS NUMBER), CAST(NULL AS NUMBER), CAST(NULL AS NUMBER), CAST(NULL AS NUMBER), CAST(NULL AS NUMBER),
         N_RSS, N_AVEC_LIGNE, N_PLUSIEURS_LIGNES, N_EGAL,
         RATIO_P05, RATIO_P25, RATIO_MED, RATIO_P75, RATIO_P95
  FROM personnes
) x
ORDER BY x.NIVEAU, x.CLE, x.CODE_GHS;
