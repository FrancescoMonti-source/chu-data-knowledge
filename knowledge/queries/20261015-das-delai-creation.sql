-- id: 20261015-das-delai-creation
-- system: cora
-- person_data: masked
-- purpose: tester si TB_DIAG.DATE_CREAT suit le codage (étape 2 du plan revu, #49) : par thème et mois de sortie des RSS MCO finis de janvier à août 2026, les DAS par délai entre la fin du RSS et leur création, ceux créés ou modifiés après M8 (2026-10-02 07:47:40), et le plus grand nombre de DAS créés un même jour
-- Oracle, schéma CORA_REC. Même population et même chemin que 20261015-m8-ecart-themes.
-- Les colonnes N_DAS_* forment une partition des DAS : pas de colonne total, pour qu'une cellule masquée ne se recalcule pas (règle 4).
-- N_DAS_MODIFIE_APRES_M8 : créé avant M8, dernière modification (DATE_INFO) après M8 ; il recoupe les autres colonnes et ne s'additionne pas avec elles.
WITH d0 AS (
  SELECT r.DATE_FIN,
         TO_CHAR(r.DATE_FIN, 'YYYY-MM') AS MOIS_SORTIE,
         d.DATE_CREAT,
         d.DATE_INFO,
         REPLACE(TRIM(d.CODE_DIAG), '.', '') AS CODE
  FROM CORA_REC.TB_SYNTH_RSS r
  JOIN CORA_REC.TB_MVT_RUM mr ON mr.ID_RSS = r.ID_RSS
  JOIN CORA_REC.TB_DIAG d ON d.ID_MVT = mr.ID_MVT
  WHERE r.DATE_FIN >= DATE '2026-01-01'
    AND r.DATE_FIN <  DATE '2026-09-01'
    AND TRIM(d.TYPE_DIAG) = 'S'
),
d1 AS (
  SELECT DATE_FIN, MOIS_SORTIE, DATE_CREAT, DATE_INFO,
         CASE
           WHEN SUBSTR(CODE, 1, 3) IN ('E40','E41','E42','E43','E44','E45','E46') THEN 'denutrition'
           WHEN CODE LIKE 'L89%' THEN 'escarres'
           WHEN CODE LIKE 'R33%' THEN 'retention_urine'
           WHEN CODE LIKE 'R521%' OR CODE LIKE 'R522%' THEN 'douleur_chronique'
           WHEN SUBSTR(CODE, 1, 3) IN ('U82','U83','U84','U85') THEN 'resistance_atb'
           WHEN CODE LIKE 'Z290%' THEN 'isolement_prophylactique'
         END AS THEME
  FROM d0
),
dx AS (
  SELECT DATE_FIN, MOIS_SORTIE, DATE_CREAT, DATE_INFO, THEME FROM d1 WHERE THEME IS NOT NULL
  UNION ALL
  SELECT DATE_FIN, MOIS_SORTIE, DATE_CREAT, DATE_INFO, 'tout_das' AS THEME FROM d0
),
agg AS (
  SELECT THEME, MOIS_SORTIE,
         SUM(CASE WHEN DATE_CREAT IS NULL THEN 1 ELSE 0 END) AS NB_SANS_DATE,
         SUM(CASE WHEN DATE_CREAT <= TIMESTAMP '2026-10-02 07:47:40' AND TRUNC(DATE_CREAT) < TRUNC(DATE_FIN) THEN 1 ELSE 0 END) AS NB_AVANT_FIN,
         SUM(CASE WHEN DATE_CREAT <= TIMESTAMP '2026-10-02 07:47:40' AND TRUNC(DATE_CREAT) - TRUNC(DATE_FIN) BETWEEN 0 AND 7 THEN 1 ELSE 0 END) AS NB_0_7J,
         SUM(CASE WHEN DATE_CREAT <= TIMESTAMP '2026-10-02 07:47:40' AND TRUNC(DATE_CREAT) - TRUNC(DATE_FIN) BETWEEN 8 AND 30 THEN 1 ELSE 0 END) AS NB_8_30J,
         SUM(CASE WHEN DATE_CREAT <= TIMESTAMP '2026-10-02 07:47:40' AND TRUNC(DATE_CREAT) - TRUNC(DATE_FIN) BETWEEN 31 AND 90 THEN 1 ELSE 0 END) AS NB_31_90J,
         SUM(CASE WHEN DATE_CREAT <= TIMESTAMP '2026-10-02 07:47:40' AND TRUNC(DATE_CREAT) - TRUNC(DATE_FIN) > 90 THEN 1 ELSE 0 END) AS NB_PLUS_90J,
         SUM(CASE WHEN DATE_CREAT > TIMESTAMP '2026-10-02 07:47:40' THEN 1 ELSE 0 END) AS NB_APRES_M8,
         SUM(CASE WHEN DATE_CREAT <= TIMESTAMP '2026-10-02 07:47:40' AND DATE_INFO > TIMESTAMP '2026-10-02 07:47:40' THEN 1 ELSE 0 END) AS NB_MODIF_APRES_M8
  FROM dx
  GROUP BY THEME, MOIS_SORTIE
),
par_jour AS (
  SELECT THEME, MOIS_SORTIE, TRUNC(DATE_CREAT) AS JOUR, COUNT(*) AS NB
  FROM dx
  WHERE DATE_CREAT IS NOT NULL
  GROUP BY THEME, MOIS_SORTIE, TRUNC(DATE_CREAT)
),
pic AS (
  SELECT THEME, MOIS_SORTIE, MAX(NB) AS NB_MAX_JOUR
  FROM par_jour
  GROUP BY THEME, MOIS_SORTIE
)
SELECT '20261015-das-delai-creation' AS query_id,
       SYS_CONTEXT('USERENV', 'DB_NAME') AS database_name,
       TO_CHAR(SYSTIMESTAMP, 'YYYY-MM-DD HH24:MI') AS run_at,
       a.THEME,
       a.MOIS_SORTIE,
       CASE WHEN a.NB_SANS_DATE < 10 THEN '<10' ELSE TO_CHAR(a.NB_SANS_DATE) END AS N_DAS_SANS_DATE,
       CASE WHEN a.NB_AVANT_FIN < 10 THEN '<10' ELSE TO_CHAR(a.NB_AVANT_FIN) END AS N_DAS_AVANT_FIN_RSS,
       CASE WHEN a.NB_0_7J < 10 THEN '<10' ELSE TO_CHAR(a.NB_0_7J) END AS N_DAS_0_7J,
       CASE WHEN a.NB_8_30J < 10 THEN '<10' ELSE TO_CHAR(a.NB_8_30J) END AS N_DAS_8_30J,
       CASE WHEN a.NB_31_90J < 10 THEN '<10' ELSE TO_CHAR(a.NB_31_90J) END AS N_DAS_31_90J,
       CASE WHEN a.NB_PLUS_90J < 10 THEN '<10' ELSE TO_CHAR(a.NB_PLUS_90J) END AS N_DAS_PLUS_90J,
       CASE WHEN a.NB_APRES_M8 < 10 THEN '<10' ELSE TO_CHAR(a.NB_APRES_M8) END AS N_DAS_APRES_M8,
       CASE WHEN a.NB_MODIF_APRES_M8 < 10 THEN '<10' ELSE TO_CHAR(a.NB_MODIF_APRES_M8) END AS N_DAS_MODIFIE_APRES_M8,
       CASE WHEN p.NB_MAX_JOUR < 10 THEN '<10' ELSE TO_CHAR(p.NB_MAX_JOUR) END AS N_DAS_MAX_UN_JOUR
FROM agg a
LEFT JOIN pic p ON p.THEME = a.THEME AND p.MOIS_SORTIE = a.MOIS_SORTIE
ORDER BY a.THEME, a.MOIS_SORTIE;
