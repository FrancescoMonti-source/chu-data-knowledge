-- id: 20261020-rhs-htp-colonnes-2025
-- system: cora
-- person_data: masked
-- purpose: pour les RHS (TB_MVT_SSR_SEM) dont la semaine débute en 2025, par TYPE_ACTIVITE et TYPE_HOSPIT_SSR, compter les RHS et les colonnes renseignées du GME, du GMT, du score de réadaptation et des montants, pour repérer les RHS de HTP et savoir où CORA range leur groupage et leur valorisation (étape 3 du plan, issue 96)
-- Oracle. Un effectif de moins de 10 sort comme <10 ; aucune ligne n'est restituée, seulement des comptages par type d'activité.
SELECT '20261020-rhs-htp-colonnes-2025' AS query_id,
       SYS_CONTEXT('USERENV', 'DB_NAME') AS database_name,
       TO_CHAR(SYSTIMESTAMP, 'YYYY-MM-DD HH24:MI') AS run_at,
       s.TYPE_ACTIVITE,
       s.TYPE_HOSPIT_SSR,
       CASE WHEN COUNT(*) < 10 THEN '<10' ELSE CAST(COUNT(*) AS VARCHAR2(12)) END AS N_RHS,
       CASE WHEN COUNT(s.CODE_GME) < 10 THEN '<10' ELSE CAST(COUNT(s.CODE_GME) AS VARCHAR2(12)) END AS N_CODE_GME,
       CASE WHEN COUNT(s.CODE_GME_SEM) < 10 THEN '<10' ELSE CAST(COUNT(s.CODE_GME_SEM) AS VARCHAR2(12)) END AS N_CODE_GME_SEM,
       CASE WHEN COUNT(CASE WHEN s.CODE_GME = s.CODE_GME_SEM THEN 1 END) < 10 THEN '<10' ELSE CAST(COUNT(CASE WHEN s.CODE_GME = s.CODE_GME_SEM THEN 1 END) AS VARCHAR2(12)) END AS N_GME_EGAL_GME_SEM,
       CASE WHEN COUNT(s.CODE_GMT) < 10 THEN '<10' ELSE CAST(COUNT(s.CODE_GMT) AS VARCHAR2(12)) END AS N_CODE_GMT,
       CASE WHEN COUNT(s.GMT_HEBDO) < 10 THEN '<10' ELSE CAST(COUNT(s.GMT_HEBDO) AS VARCHAR2(12)) END AS N_GMT_HEBDO,
       CASE WHEN COUNT(s.SCORE_RR) < 10 THEN '<10' ELSE CAST(COUNT(s.SCORE_RR) AS VARCHAR2(12)) END AS N_SCORE_RR,
       CASE WHEN COUNT(s.SCORE_RR_SEM) < 10 THEN '<10' ELSE CAST(COUNT(s.SCORE_RR_SEM) AS VARCHAR2(12)) END AS N_SCORE_RR_SEM,
       CASE WHEN COUNT(s.PONDERATION_RR_RHS) < 10 THEN '<10' ELSE CAST(COUNT(s.PONDERATION_RR_RHS) AS VARCHAR2(12)) END AS N_PONDERATION_RR_RHS,
       CASE WHEN COUNT(s.NBJ_PRES) < 10 THEN '<10' ELSE CAST(COUNT(s.NBJ_PRES) AS VARCHAR2(12)) END AS N_NBJ_PRES,
       CASE WHEN COUNT(s.MNT_GMT) < 10 THEN '<10' ELSE CAST(COUNT(s.MNT_GMT) AS VARCHAR2(12)) END AS N_MNT_GMT,
       CASE WHEN COUNT(s.MNT_GMT_HEBDO) < 10 THEN '<10' ELSE CAST(COUNT(s.MNT_GMT_HEBDO) AS VARCHAR2(12)) END AS N_MNT_GMT_HEBDO,
       CASE WHEN COUNT(s.MNT_TOTAL) < 10 THEN '<10' ELSE CAST(COUNT(s.MNT_TOTAL) AS VARCHAR2(12)) END AS N_MNT_TOTAL,
       CASE WHEN COUNT(CASE WHEN s.STATUT_GROUPAGE = 'G' THEN 1 END) < 10 THEN '<10' ELSE CAST(COUNT(CASE WHEN s.STATUT_GROUPAGE = 'G' THEN 1 END) AS VARCHAR2(12)) END AS N_GROUPE
FROM CORA_REC.TB_MVT_SSR_SEM s
WHERE s.DATE_DEBUT_SEM >= DATE '2025-01-01' AND s.DATE_DEBUT_SEM < DATE '2026-01-01'
GROUP BY s.TYPE_ACTIVITE, s.TYPE_HOSPIT_SSR
ORDER BY s.TYPE_ACTIVITE, s.TYPE_HOSPIT_SSR;
