-- id: 20261014-sorties-manquantes
-- system: cora
-- person_data: masked
-- purpose: par année d'entrée, séjours sans DATE_SORTIE, leur profil (préadmission, mouvement unique resté ouvert sans RSS), la source qui permettrait d'imputer leur sortie (fin du RSS, fin ou début du dernier mouvement, entrée), et, sur les séjours complets, l'accord entre la sortie et la fin du dernier mouvement ou du RSS (étape 3 du plan, #24)
-- Oracle, schéma CORA_REC. Séjours entrés de 2014 à 2025 : tous entrés depuis plus de 90 jours, donc non « en cours ».
-- Dernier mouvement : le plus tardif par DATE_DEBUT_MVT, HEURE_DEBUT_MVT, ID_MVT. RSS : par TB_MVT → TB_MVT_RUM → TB_SYNTH_RSS.
-- Masquage : chaque effectif < 10 sort en <10. Suppression secondaire (règle 4) : N_SEJ et N_SANS_SORTIE sortent en « masqué » dès qu'une case de leurs partitions (N_IMPUT_…, N_COMPLET_…) ou un complément (N_SANS_SORTIE moins un sous-ensemble) est sous 10 ; N_COMPLET_AVEC_RSS sort en « masqué » si N_COMPLET_RSS_MEME_JOUR en diffère de moins de 10.
WITH mv AS (
  SELECT ID_SEJOUR,
         COUNT(*) AS NB_MVT,
         SUM(CASE WHEN DATE_FIN_MVT IS NULL THEN 1 ELSE 0 END) AS NB_OUVERTS,
         MAX(DATE_DEBUT_MVT) AS DERNIER_DEBUT,
         MAX(DATE_FIN_MVT) KEEP (DENSE_RANK LAST ORDER BY DATE_DEBUT_MVT, HEURE_DEBUT_MVT, ID_MVT) AS DERNIERE_FIN
  FROM CORA_REC.TB_MVT
  GROUP BY ID_SEJOUR
),
rs AS (
  SELECT m.ID_SEJOUR, MAX(r.DATE_FIN) AS FIN_RSS
  FROM CORA_REC.TB_MVT m
  JOIN CORA_REC.TB_MVT_RUM mr ON mr.ID_MVT = m.ID_MVT
  JOIN CORA_REC.TB_SYNTH_RSS r ON r.ID_RSS = mr.ID_RSS
  GROUP BY m.ID_SEJOUR
),
s AS (
  SELECT EXTRACT(YEAR FROM se.DATE_ENTREE) AS ANNEE_ENTREE,
         CASE WHEN se.DATE_SORTIE IS NULL THEN 1 ELSE 0 END AS SANS,
         se.DATE_SORTIE, se.STATUT_PROG,
         mv.NB_MVT, mv.NB_OUVERTS, mv.DERNIER_DEBUT, mv.DERNIERE_FIN, rs.FIN_RSS
  FROM CORA_REC.TB_SEJOUR se
  LEFT JOIN mv ON mv.ID_SEJOUR = se.ID_SEJOUR
  LEFT JOIN rs ON rs.ID_SEJOUR = se.ID_SEJOUR
  WHERE se.DATE_ENTREE >= DATE '2014-01-01'
    AND se.DATE_ENTREE < DATE '2026-01-01'
),
a AS (
  SELECT ANNEE_ENTREE,
         COUNT(*) AS SEJ,
         SUM(SANS) AS SANS_SORTIE,
         SUM(CASE WHEN SANS = 1 AND STATUT_PROG = 'P' THEN 1 ELSE 0 END) AS SANS_PREADM,
         SUM(CASE WHEN SANS = 1 AND NB_MVT = 1 AND NB_OUVERTS = 1 AND FIN_RSS IS NULL THEN 1 ELSE 0 END) AS SANS_UN_MVT_OUVERT,
         SUM(CASE WHEN SANS = 1 AND FIN_RSS IS NOT NULL THEN 1 ELSE 0 END) AS I_RSS,
         SUM(CASE WHEN SANS = 1 AND FIN_RSS IS NULL AND DERNIERE_FIN IS NOT NULL THEN 1 ELSE 0 END) AS I_FIN_MVT,
         SUM(CASE WHEN SANS = 1 AND FIN_RSS IS NULL AND DERNIERE_FIN IS NULL AND DERNIER_DEBUT IS NOT NULL THEN 1 ELSE 0 END) AS I_DEBUT_MVT,
         SUM(CASE WHEN SANS = 1 AND FIN_RSS IS NULL AND DERNIERE_FIN IS NULL AND DERNIER_DEBUT IS NULL THEN 1 ELSE 0 END) AS I_ENTREE,
         SUM(CASE WHEN SANS = 0 AND TRUNC(DERNIERE_FIN) = TRUNC(DATE_SORTIE) THEN 1 ELSE 0 END) AS C_MVT_MEME_JOUR,
         SUM(CASE WHEN SANS = 0 AND (DERNIERE_FIN IS NULL OR TRUNC(DERNIERE_FIN) <> TRUNC(DATE_SORTIE)) THEN 1 ELSE 0 END) AS C_MVT_AUTRE,
         SUM(CASE WHEN SANS = 0 AND FIN_RSS IS NOT NULL THEN 1 ELSE 0 END) AS C_RSS,
         SUM(CASE WHEN SANS = 0 AND TRUNC(FIN_RSS) = TRUNC(DATE_SORTIE) THEN 1 ELSE 0 END) AS C_RSS_MEME_JOUR
  FROM s
  GROUP BY ANNEE_ENTREE
),
f AS (
  SELECT a.*,
         CASE WHEN LEAST(I_RSS, I_FIN_MVT, I_DEBUT_MVT, I_ENTREE, C_MVT_MEME_JOUR, C_MVT_AUTRE,
                         SANS_SORTIE - SANS_PREADM, SANS_SORTIE - SANS_UN_MVT_OUVERT) < 10
              THEN 1 ELSE 0 END AS MASQUER_TOTAUX
  FROM a
)
SELECT '20261014-sorties-manquantes' AS query_id,
       SYS_CONTEXT('USERENV', 'DB_NAME') AS database_name,
       TO_CHAR(SYSTIMESTAMP, 'YYYY-MM-DD HH24:MI') AS run_at,
       ANNEE_ENTREE,
       CASE WHEN SEJ < 10 THEN '<10' WHEN MASQUER_TOTAUX = 1 THEN 'masqué' ELSE TO_CHAR(SEJ) END AS N_SEJ,
       CASE WHEN SANS_SORTIE < 10 THEN '<10' WHEN MASQUER_TOTAUX = 1 THEN 'masqué' ELSE TO_CHAR(SANS_SORTIE) END AS N_SANS_SORTIE,
       CASE WHEN SANS_PREADM < 10 THEN '<10' ELSE TO_CHAR(SANS_PREADM) END AS N_SANS_SORTIE_PREADM,
       CASE WHEN SANS_UN_MVT_OUVERT < 10 THEN '<10' ELSE TO_CHAR(SANS_UN_MVT_OUVERT) END AS N_SANS_SORTIE_UN_MVT_OUVERT,
       CASE WHEN I_RSS < 10 THEN '<10' ELSE TO_CHAR(I_RSS) END AS N_IMPUT_FIN_RSS,
       CASE WHEN I_FIN_MVT < 10 THEN '<10' ELSE TO_CHAR(I_FIN_MVT) END AS N_IMPUT_FIN_MVT,
       CASE WHEN I_DEBUT_MVT < 10 THEN '<10' ELSE TO_CHAR(I_DEBUT_MVT) END AS N_IMPUT_DEBUT_MVT,
       CASE WHEN I_ENTREE < 10 THEN '<10' ELSE TO_CHAR(I_ENTREE) END AS N_IMPUT_ENTREE,
       CASE WHEN C_MVT_MEME_JOUR < 10 THEN '<10' ELSE TO_CHAR(C_MVT_MEME_JOUR) END AS N_COMPLET_MVT_MEME_JOUR,
       CASE WHEN C_MVT_AUTRE < 10 THEN '<10' ELSE TO_CHAR(C_MVT_AUTRE) END AS N_COMPLET_MVT_AUTRE,
       CASE WHEN C_RSS < 10 THEN '<10' WHEN C_RSS - C_RSS_MEME_JOUR < 10 THEN 'masqué' ELSE TO_CHAR(C_RSS) END AS N_COMPLET_AVEC_RSS,
       CASE WHEN C_RSS_MEME_JOUR < 10 THEN '<10' ELSE TO_CHAR(C_RSS_MEME_JOUR) END AS N_COMPLET_RSS_MEME_JOUR
FROM f
ORDER BY ANNEE_ENTREE;
