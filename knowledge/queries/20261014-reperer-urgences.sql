-- id: 20261014-reperer-urgences
-- system: cora
-- person_data: masked
-- purpose: pour chaque UF candidate aux urgences, comparer les signaux qui repèrent un passage aux urgences (drapeau URGENCE de TB_UNITE, TB_SEJOUR.UF_URGENCE, TYPE_SEJOUR = 'URG') (étape 11 du plan, #24)
-- Oracle, schéma CORA_REC. UF candidate : drapeau URGENCE = 'O', libellé contenant URG, code présent dans TB_SEJOUR.UF_URGENCE, ou UF d'entrée d'un séjour de TYPE_SEJOUR 'URG'.
-- CODE_UNITE n'est pas unique dans TB_UNITE : les drapeaux sont comptés par ligne (LIGNES_…), jamais joints directement.
-- Deux périodes d'entrée, 2014-2019 et 2020-2025 : TYPE_SEJOUR change de codage en 2020 (type-sejour-non-fiable).
WITH u AS (
  SELECT TRIM(CODE_UNITE) AS CODE_UNITE,
         MAX(LIBELLE_UNITE) AS LIBELLE_UNITE,
         COUNT(*) AS LIGNES_UNITE,
         SUM(CASE WHEN URGENCE = 'O' THEN 1 ELSE 0 END) AS LIGNES_URGENCE_O,
         SUM(CASE WHEN GESTION_PMSI = 'O' THEN 1 ELSE 0 END) AS LIGNES_GESTION_PMSI_O,
         SUM(CASE WHEN UHCD = 'O' THEN 1 ELSE 0 END) AS LIGNES_UHCD_O,
         SUM(CASE WHEN EXTERNE = 'O' THEN 1 ELSE 0 END) AS LIGNES_EXTERNE_O,
         SUM(CASE WHEN ACTIF = 'O' THEN 1 ELSE 0 END) AS LIGNES_ACTIF_O
  FROM CORA_REC.TB_UNITE
  GROUP BY TRIM(CODE_UNITE)
),
s AS (
  SELECT CASE WHEN DATE_ENTREE < DATE '2020-01-01' THEN '2014-2019' ELSE '2020-2025' END AS PERIODE,
         TRIM(UF_ENTREE) AS UF_ENTREE,
         TRIM(UF_URGENCE) AS UF_URGENCE,
         TRIM(TYPE_SEJOUR) AS TYPE_SEJOUR
  FROM CORA_REC.TB_SEJOUR
  WHERE DATE_ENTREE >= DATE '2014-01-01'
    AND DATE_ENTREE < DATE '2026-01-01'
),
e AS (
  SELECT PERIODE, UF_ENTREE AS CODE_UNITE,
         COUNT(*) AS NB,
         SUM(CASE WHEN TYPE_SEJOUR = 'URG' THEN 1 ELSE 0 END) AS NB_URG
  FROM s
  GROUP BY PERIODE, UF_ENTREE
),
g AS (
  SELECT PERIODE, UF_URGENCE AS CODE_UNITE, COUNT(*) AS NB
  FROM s
  WHERE UF_URGENCE IS NOT NULL
  GROUP BY PERIODE, UF_URGENCE
),
c AS (
  SELECT CODE_UNITE FROM u WHERE LIGNES_URGENCE_O > 0 OR UPPER(LIBELLE_UNITE) LIKE '%URG%'
  UNION
  SELECT CODE_UNITE FROM g
  UNION
  SELECT CODE_UNITE FROM e WHERE NB_URG > 0
),
p AS (
  SELECT '2014-2019' AS PERIODE FROM DUAL
  UNION ALL
  SELECT '2020-2025' FROM DUAL
)
SELECT '20261014-reperer-urgences' AS query_id,
       SYS_CONTEXT('USERENV', 'DB_NAME') AS database_name,
       TO_CHAR(SYSTIMESTAMP, 'YYYY-MM-DD HH24:MI') AS run_at,
       c.CODE_UNITE,
       u.LIBELLE_UNITE,
       u.LIGNES_UNITE,
       u.LIGNES_URGENCE_O,
       u.LIGNES_GESTION_PMSI_O,
       u.LIGNES_UHCD_O,
       u.LIGNES_EXTERNE_O,
       u.LIGNES_ACTIF_O,
       p.PERIODE,
       CASE WHEN NVL(e.NB, 0) < 10 THEN '<10' ELSE TO_CHAR(e.NB) END AS N_SEJ_UF_ENTREE,
       CASE WHEN NVL(e.NB_URG, 0) < 10 THEN '<10' ELSE TO_CHAR(e.NB_URG) END AS N_SEJ_UF_ENTREE_TYPE_URG,
       CASE WHEN NVL(g.NB, 0) < 10 THEN '<10' ELSE TO_CHAR(g.NB) END AS N_SEJ_UF_URGENCE
FROM c
CROSS JOIN p
LEFT JOIN u ON u.CODE_UNITE = c.CODE_UNITE
LEFT JOIN e ON e.CODE_UNITE = c.CODE_UNITE AND e.PERIODE = p.PERIODE
LEFT JOIN g ON g.CODE_UNITE = c.CODE_UNITE AND g.PERIODE = p.PERIODE
ORDER BY c.CODE_UNITE, p.PERIODE;
